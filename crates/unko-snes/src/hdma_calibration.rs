/// Table for setup phase 0/2/4/6.
pub fn table(phase: u32) -> &'static [u32; LINES] {
    &TABLES[((phase & 6) as usize) >> 1]
}

/// Setup phase recorded by ares for a PPU frame, when calibrated.
pub fn phase_for(frame: u64) -> Option<u32> {
    PHASES
        .iter()
        .find(|(f, _)| u64::from(*f) == frame)
        .map(|(_, p)| *p)
}
