//! SPC700 instruction timing against the RustySNES (ares-derived) oracle.
//!
//! Each entry is the total S-SMP base clocks (2.048 MHz) an opcode costs,
//! measured from `RustySNES`'s cycle-accurate dispatch with the register
//! state below. The four states exercise both directions of every branch.
//! `unko-snes` counts accesses (two clocks each), so the assertion doubles
//! the measured units.

use unko_snes::spc700::{Spc700, SpcBus};

struct Ram {
    data: Vec<u8>,
}

impl Ram {
    fn new() -> Self {
        Self {
            data: vec![0; 0x1_0000],
        }
    }
}

impl SpcBus for Ram {
    fn read(&mut self, address: u16) -> u8 {
        self.data[address as usize]
    }

    fn write(&mut self, address: u16, value: u8) {
        self.data[address as usize] = value;
    }
}

