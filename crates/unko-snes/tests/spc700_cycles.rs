#[test]
fn opcode_cycles_match_the_oracle() {
    for (state, (a, x, y, psw, sp)) in STATES.iter().enumerate() {
        for opcode in 0u8..=255 {
            let mut cpu = Spc700::new();
            let mut ram = Ram::new();
            ram.data[0x200] = opcode;
            ram.data[0x201] = 0x10;
            ram.data[0x202] = 0x20;
            cpu.pc = 0x0200;
            cpu.a = *a;
            cpu.x = *x;
            cpu.y = *y;
            cpu.sp = *sp;
            cpu.set_psw(*psw);
            let clocks = cpu.step(&mut ram) * 2;
            assert_eq!(
                clocks,
                u32::from(ORACLE[state][usize::from(opcode)]),
                "state {state} opcode {opcode:02X}"
            );
        }
    }
}
